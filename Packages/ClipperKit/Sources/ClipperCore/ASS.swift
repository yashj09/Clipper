import Foundation

extension Subtitles {
    /// Advanced SubStation Alpha (v4+) subtitles that keep the caption styling: font, size, colours, outline/box,
    /// shadow, placement and the moving active-word highlight (as `\k` karaoke).
    ///
    /// - Parameters:
    ///   - track: one caption track (exported even if hidden); nil = every visible caption track.
    ///   - fontName: maps a style's PostScript font name to the name written into the style line.
    public static func ass(_ timeline: Timeline, track: TrackID? = nil,
                           fontName: (String) -> String = ASS.fullName(postScript:)) -> String {
        let tracks = track.map { id in timeline.tracks.filter { $0.id == id && $0.kind == .caption } } ?? visibleTracks(timeline)
        return ass(timeline, tracks: tracks, fontName: fontName)
    }

    /// ASS for every caption track tagged `language` (hidden or not).
    public static func ass(_ timeline: Timeline, language: String,
                           fontName: (String) -> String = ASS.fullName(postScript:)) -> String {
        ass(timeline, tracks: tracks(timeline, language: language), fontName: fontName)
    }

    static func ass(_ timeline: Timeline, tracks: [Track], fontName: (String) -> String) -> String {
        let canvas = timeline.canvas
        var events: [(start: Int, layer: Int, line: String)] = []
        var used: [String: TextStyle] = [:]
        for (layer, track) in tracks.enumerated() {
            for item in track.items {
                guard case .caption(let caption) = item.content, !caption.words.isEmpty else { continue }
                let name = ASS.styleName(caption.style)
                let style = timeline.styles[caption.style] ?? TextStyle()
                used[name] = style
                let start = ASS.centiseconds(item.start), end = max(ASS.centiseconds(item.end), start)
                let text = ASS.dialogueText(caption, style: style, length: end - start, language: track.language)
                events.append((start, layer, "Dialogue: \(layer),\(ASS.timestamp(centiseconds: start)),\(ASS.timestamp(centiseconds: end)),\(name),,0,0,0,,\(text)"))
            }
        }
        events.sort { ($0.start, $0.layer) < ($1.start, $1.layer) }

        var out = """
        [Script Info]
        ; Generated by Clipper
        Title: \(timeline.name.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "\r", with: " "))
        ScriptType: v4.00+
        WrapStyle: 0
        ScaledBorderAndShadow: yes
        YCbCr Matrix: TV.709
        PlayResX: \(canvas.width)
        PlayResY: \(canvas.height)

        [V4+ Styles]
        Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding

        """
        for name in used.keys.sorted() {
            out += ASS.styleLine(name: name, style: used[name]!, canvas: canvas, fontName: fontName) + "\n"
        }
        out += "\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
        for e in events { out += e.line + "\n" }
        return out
    }
}

/// Building blocks of the ASS writer (exposed for tests and for callers composing their own scripts).
///
/// Karaoke mapping: in ASS, `\k` switches a word from `SecondaryColour` to `PrimaryColour` when its time comes and the
/// word *keeps* that colour. Clipper's renderer highlights only the word being spoken, so karaoke styles use the
/// highlight colour as `PrimaryColour` and the text colour as `SecondaryColour`, and each word carries a `\t` that
/// turns it back to its own colour when the next word starts. Players without `\t` support still show a left-to-right fill.
public enum ASS {
    // MARK: Colours

    /// Style colour `&HAABBGGRR`. ASS alpha is inverted: 00 = opaque, FF = fully transparent.
    public static func colour(_ c: RGBA) -> String {
        String(format: "&H%02X%02X%02X%02X", byte(1 - c.a), byte(c.b), byte(c.g), byte(c.r))
    }

    /// Override-tag colour `&HBBGGRR&` (no alpha; ASS sets alpha with separate tags).
    public static func inlineColour(_ c: RGBA) -> String {
        String(format: "&H%02X%02X%02X&", byte(c.b), byte(c.g), byte(c.r))
    }

    static func byte(_ x: Double) -> Int { Int((min(max(x, 0), 1) * 255).rounded()) }

    // MARK: Time

    public static func centiseconds(_ t: RationalTime) -> Int { Int((t.seconds * 100).rounded()) }

    /// `H:MM:SS.cc`
    public static func timestamp(centiseconds cs: Int) -> String {
        let cs = max(cs, 0)
        return String(format: "%d:%02d:%02d.%02d", cs / 360_000, cs / 6000 % 60, cs / 100 % 60, cs % 100)
    }

    /// `\k` durations (centiseconds) for a page of `length` cs. Word *i* is active from its start until the next word
    /// starts (the first from the page start, the last until the page end) — the same rule as the renderer — so the
    /// durations always sum to exactly `length`.
    public static func karaokeDurations(_ words: [CaptionContent.Word], length: Int) -> [Int] {
        guard !words.isEmpty else { return [] }
        var bounds = [0]
        for w in words.dropFirst() { bounds.append(min(max(centiseconds(w.start), bounds.last!), length)) }
        bounds.append(max(length, bounds.last!))
        return zip(bounds.dropFirst(), bounds).map { $0 - $1 }
    }

    // MARK: Layout

    /// Numpad alignment (1–3 bottom, 4–6 middle, 7–9 top; left/centre/right in each row). The row comes from
    /// `position.y`: within 0.05 of the centre → middle, above → top, below → bottom.
    public static func alignment(_ style: TextStyle) -> Int {
        let column = switch style.alignment {
        case .left: 1
        case .center: 2
        case .right: 3
        }
        let y = style.position.y
        let row = abs(y - 0.5) <= 0.05 ? 3 : (y < 0.5 ? 6 : 0)
        return column + row
    }

    /// Distance from the anchored edge to the text, placing a one-line page's centre at `position.y`
    /// (ignored by ASS for the middle row).
    public static func marginV(_ style: TextStyle, canvas: Canvas) -> Int {
        let h = Double(canvas.height), half = style.size * h / 2
        let m: Double = switch alignment(style) {
        case 7...9: style.position.y * h - half
        case 1...3: (1 - style.position.y) * h - half
        default: 0
        }
        return max(0, Int(m.rounded()))
    }

    /// Left/right margins so lines wrap within `maxWidth` of the canvas, centred on `position.x`.
    public static func marginsLR(_ style: TextStyle, canvas: Canvas) -> (left: Int, right: Int) {
        let w = Double(canvas.width), half = style.maxWidth / 2
        return (max(0, Int(((style.position.x - half) * w).rounded())), max(0, Int(((1 - style.position.x - half) * w).rounded())))
    }

    // MARK: Fonts

    /// Full font name from a PostScript name: "AvenirNext-Heavy" → "Avenir Next Heavy", "Helvetica-Bold" →
    /// "Helvetica Bold", "Foo-Regular" → "Foo". libass matches full names, so the exact weight is picked.
    public static func fullName(postScript: String) -> String {
        let parts = postScript.split(separator: "-", maxSplits: 1).map { splitCamel(String($0)) }
        guard parts.count == 2, !["Regular", "Roman", "Book", "Normal"].contains(parts[1]) else { return parts.first ?? postScript }
        return parts.joined(separator: " ")
    }

    static func splitCamel(_ s: String) -> String {
        var out = ""
        let chars = Array(s)
        for (i, c) in chars.enumerated() {
            if i > 0, c.isUppercase {
                let prev = chars[i - 1], next = i + 1 < chars.count ? chars[i + 1] : nil
                if prev.isLowercase || (prev.isUppercase && next?.isLowercase == true) { out.append(" ") }
            }
            out.append(c)
        }
        return out
    }

    static func weightTokens(_ postScript: String) -> String {
        postScript.split(separator: "-", maxSplits: 1).dropFirst().first.map { $0.lowercased() } ?? ""
    }

    public static func isBold(postScript: String) -> Bool {
        let w = weightTokens(postScript)
        return ["bold", "heavy", "black", "semibold", "demi", "ultra", "extrabold"].contains { w.contains($0) }
    }

    public static func isItalic(postScript: String) -> Bool {
        let w = weightTokens(postScript)
        return w.contains("italic") || w.contains("oblique")
    }

    // MARK: Styles

    /// ASS style names can't contain commas.
    static func styleName(_ name: String) -> String {
        let s = name.replacingOccurrences(of: ",", with: ";").trimmingCharacters(in: .whitespaces)
        return s.isEmpty ? "Default" : s
    }

    /// The colour the spoken word takes. A highlight that only adds a box (same text colour) uses the box colour
    /// for the text, since per-word boxes have no ASS equivalent.
    static func karaokeColour(_ style: TextStyle) -> RGBA? {
        guard let h = style.highlight else { return nil }
        if let c = h.color, c != style.color { return c }
        return h.box ?? h.color ?? style.color
    }

    /// `Style:` line. Sizes scale with the canvas height (`PlayResY`); outline = strokeWidth × size, shadow depth =
    /// the shadow offset × size; a background box becomes BorderStyle 3 (opaque box) with the box colour.
    public static func styleLine(name: String, style: TextStyle, canvas: Canvas,
                                 fontName: (String) -> String = fullName(postScript:)) -> String {
        let size = style.size * Double(canvas.height)
        let karaoke = karaokeColour(style)
        let primary = karaoke ?? style.color
        let secondary = style.color
        let outlineColour: RGBA, back: RGBA, border: Int, outline: Double, shadow: Double
        if let box = style.box {
            border = 3; outlineColour = box.color; back = box.color; outline = box.padding * size; shadow = 0
        } else {
            border = 1
            outlineColour = style.stroke ?? .black
            outline = style.stroke == nil ? 0 : style.strokeWidth * size
            back = style.shadow?.color ?? RGBA(0, 0, 0, 0)
            shadow = style.shadow.map { max(abs($0.offset.x), abs($0.offset.y)) * size } ?? 0
        }
        let (ml, mr) = marginsLR(style, canvas: canvas)
        let fields: [String] = [
            name, fontName(style.font).replacingOccurrences(of: ",", with: " "), number(size),
            colour(primary), colour(secondary), colour(outlineColour), colour(back),
            isBold(postScript: style.font) ? "-1" : "0", isItalic(postScript: style.font) ? "-1" : "0", "0", "0",
            "100", "100", "0", "0", "\(border)", number(outline), number(shadow),
            "\(alignment(style))", "\(ml)", "\(mr)", "\(marginV(style, canvas: canvas))", "1",
        ]
        return "Style: " + fields.joined(separator: ",")
    }

    // MARK: Events

    /// Dialogue text for one caption page of `length` centiseconds.
    static func dialogueText(_ caption: CaptionContent, style: TextStyle, length: Int, language: String?) -> String {
        let words = caption.words.map { style.uppercase ? $0.text.uppercased() : $0.text }.map(escape)
        let separator = CaptionLanguage.usesWordSpaces(language) ? " " : ""
        func colour(of i: Int) -> RGBA {
            caption.words[i].emphasis ? (style.emphasisColor ?? style.color) : style.color
        }
        guard let highlight = karaokeColour(style) else {
            return words.enumerated().map { i, w in
                caption.words[i].emphasis && style.emphasisColor != nil ? "{\\c\(inlineColour(colour(of: i)))}\(w){\\r}" : w
            }.joined(separator: separator)
        }
        let durations = karaokeDurations(caption.words, length: length)
        var secondary = style.color
        var elapsed = 0
        var parts: [String] = []
        for (i, w) in words.enumerated() {
            let own = colour(of: i)
            var tags = "\\k\(durations[i])"
            // Earlier words' \t tags changed the running primary colour: restore the highlight for this word.
            if i > 0 { tags += "\\1c\(inlineColour(highlight))" }
            if own != secondary { tags += "\\2c\(inlineColour(own))"; secondary = own }
            elapsed += durations[i]
            if i < words.count - 1 {
                let ms = elapsed * 10
                tags += "\\t(\(ms),\(ms + 1),\\1c\(inlineColour(own)))"
            }
            parts.append("{\(tags)}\(w)")
        }
        return parts.joined(separator: separator)
    }

    /// Makes caption text literal: braces would start override blocks and line breaks would end the event.
    /// Backslashes become a full-width reverse solidus so `\N`, `\h` etc. can't appear by accident.
    public static func escape(_ text: String) -> String {
        var out = ""
        for ch in text {
            switch ch {
            case "{": out += "\\{"
            case "}": out += "\\}"
            case "\\": out += "\u{FF3C}"
            case "\n", "\r", "\r\n": out += "\\N"
            default: out.append(ch)
            }
        }
        return out
    }

    /// Up to two decimals, no trailing zeros.
    static func number(_ x: Double) -> String {
        var s = String(format: "%.2f", x)
        while s.hasSuffix("0") { s.removeLast() }
        if s.hasSuffix(".") { s.removeLast() }
        return s == "-0" ? "0" : s
    }
}
